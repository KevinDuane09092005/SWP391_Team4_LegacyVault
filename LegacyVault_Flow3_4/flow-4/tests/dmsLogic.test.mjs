import test from 'node:test';
import assert from 'node:assert/strict';
import {computeDmsView} from '../src/dmsLogic.mjs';
const day=86400000;
const now=Date.parse('2026-10-13T00:00:00Z');
const state=({offset,grace=14,status,api=false,configured=true,apiError=''})=>computeDmsView({configured,now,nextCheckIn:new Date(now+offset*day),graceEndsAt:new Date(now+(offset+grace)*day),backendStatus:status,apiEnabled:api,apiError});
test('unconfigured local state shows config',()=>assert.equal(state({offset:10,configured:false}),'config'));
test('local more than three days due is monitoring',()=>assert.equal(state({offset:8}),'active'));
test('local less than three days due is due soon',()=>assert.equal(state({offset:2}),'soon'));
test('local boundary three days due is due soon',()=>assert.equal(state({offset:3}),'soon'));
test('local missed checkin enters grace',()=>assert.equal(state({offset:-1}),'warning'));
test('local expired grace shows triggered',()=>assert.equal(state({offset:-15}),'triggered'));
test('backend lowercase active maps to monitoring',()=>assert.equal(state({offset:8,status:'active',api:true}),'active'));
test('backend active close to deadline maps to due soon',()=>assert.equal(state({offset:2,status:'active',api:true}),'soon'));
test('backend warning means grace, not due soon',()=>assert.equal(state({offset:-1,status:'warning',api:true}),'warning'));
test('backend triggered is triggered regardless of client timer',()=>assert.equal(state({offset:5,status:'triggered',api:true}),'triggered'));
test('backend unavailable never silently falls back to local status',()=>assert.equal(state({offset:-15,api:true,apiError:'Network error'}),'error'));
test('backend active despite expired next due is ambiguous, not triggered',()=>assert.equal(state({offset:-1,status:'active',api:true}),'error'));
test('missing backend status is unknown',()=>assert.equal(state({offset:9,api:true}),'error'));
